"""Builds the human-readable and machine-readable generation reports."""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from typing import Dict, List, Tuple

from .controllers import ExtractionResult
from .schemas import SchemaRegistry


def _relative(path: str, repo_root: str) -> str:
    return path[len(repo_root) :].lstrip("/") if path.startswith(repo_root) else path


def build_json_report(
    result: ExtractionResult,
    registry: SchemaRegistry,
    summary_report: List[Tuple[str, str, str]],
    path_conflicts: List[str],
    files_written: List[str],
    repo_root: str,
) -> Dict[str, object]:
    generated = [row for row in summary_report if row[2] == "generated"]
    curated = [row for row in summary_report if row[2] == "curated"]
    by_module: Counter = Counter(endpoint.module for endpoint in result.endpoints)
    by_verb: Counter = Counter(endpoint.http_method.upper() for endpoint in result.endpoints)
    by_media: Counter = Counter(endpoint.produces for endpoint in result.endpoints)
    exclusion_reasons: Counter = Counter(exclusion.reason for exclusion in result.exclusions)

    return {
        "totals": {
            "controllers_scanned": len(result.controllers),
            "endpoints_emitted": len(result.endpoints),
            "endpoints_excluded": len(result.exclusions),
            "inherited_endpoints": sum(1 for e in result.endpoints if e.inherited),
            "schemas_generated": len(registry.schemas),
            "summaries_generated": len(generated),
            "summaries_curated": len(curated),
            "unresolved_types": len(registry.unresolved),
            "opaque_type_uses": len(registry.opaque),
            "unbound_parameters": len(result.unbound_params),
            "parse_failures": 0,
        },
        "endpoints_by_module": dict(sorted(by_module.items())),
        "endpoints_by_verb": dict(sorted(by_verb.items())),
        "endpoints_by_media_type": dict(sorted(by_media.items())),
        "exclusion_reasons": dict(sorted(exclusion_reasons.items())),
        "exclusions": [
            {
                "controller": exclusion.controller,
                "method": exclusion.method,
                "path": exclusion.path,
                "reason": exclusion.reason,
                "file": _relative(exclusion.file, repo_root),
            }
            for exclusion in sorted(result.exclusions, key=lambda e: (e.controller, e.method))
        ],
        "unresolved_types": [
            {"type": item.type_name, "context": item.context, "reason": item.reason}
            for item in sorted(registry.unresolved, key=lambda i: (i.type_name, i.context))
        ],
        "opaque_types": [
            {"type": item.type_name, "context": item.context, "reason": item.reason}
            for item in sorted(registry.opaque, key=lambda i: (i.type_name, i.context))
        ],
        "unbound_parameters": [
            {"source": source, "parameter": parameter, "path": path}
            for source, parameter, path in sorted(result.unbound_params)
        ],
        "summaries_needing_curation": [
            {"source": source, "summary": summary}
            for source, summary, origin in summary_report
            if origin == "generated"
        ],
        "path_conflicts": path_conflicts,
        "files_written": files_written,
        "endpoints": [
            {
                "method": endpoint.http_method.upper(),
                "path": endpoint.path,
                "controller": endpoint.controller.simple_name,
                "source": endpoint.source,
                "inherited": endpoint.inherited,
                "produces": endpoint.produces,
                "module": endpoint.module,
                "return_type": endpoint.return_type.render() if endpoint.return_type else "void",
                "notes": endpoint.notes,
            }
            for endpoint in sorted(result.endpoints, key=lambda e: (e.path, e.http_method))
        ],
    }


def _table(headers: List[str], rows: List[List[str]]) -> List[str]:
    if not rows:
        return ["_(none)_", ""]
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    lines.extend("| " + " | ".join(cell.replace("|", "\\|") for cell in row) + " |" for row in rows)
    lines.append("")
    return lines


def build_markdown_report(data: Dict[str, object]) -> str:
    totals = data["totals"]
    lines: List[str] = [
        "# qcadoo MES OpenAPI generation report",
        "",
        "Generated by `mes-bdd-tests/tools/generate_openapi.py` (static AST analysis, javalang).",
        "",
        "## Totals",
        "",
    ]
    lines.extend(
        _table(
            ["Metric", "Value"],
            [[key.replace("_", " "), str(value)] for key, value in totals.items()],
        )
    )

    lines.append("## Endpoints by module")
    lines.append("")
    lines.extend(
        _table(
            ["Module", "Endpoints"],
            [[key, str(value)] for key, value in data["endpoints_by_module"].items()],
        )
    )

    lines.append("## Endpoints by HTTP verb")
    lines.append("")
    lines.extend(
        _table(
            ["Verb", "Endpoints"],
            [[key, str(value)] for key, value in data["endpoints_by_verb"].items()],
        )
    )

    lines.append("## Endpoints by response media type")
    lines.append("")
    lines.extend(
        _table(
            ["Media type", "Endpoints"],
            [[key, str(value)] for key, value in data["endpoints_by_media_type"].items()],
        )
    )

    lines.append("## Excluded endpoints")
    lines.append("")
    lines.append(
        "Methods carrying `@RequestMapping` that are deliberately kept out of the API spec."
    )
    lines.append("")
    lines.extend(
        _table(
            ["Reason", "Count"],
            [[key, str(value)] for key, value in data["exclusion_reasons"].items()],
        )
    )
    lines.extend(
        _table(
            ["Controller", "Method", "Path", "Reason"],
            [
                [row["controller"], row["method"], f"`{row['path']}`", row["reason"]]
                for row in data["exclusions"]
            ],
        )
    )

    lines.append("## Types that degraded to `type: object`")
    lines.append("")
    lines.append(
        "These could not be expanded into a schema, so the payload shape is not described."
    )
    lines.append("")
    grouped: Dict[str, List[str]] = defaultdict(list)
    for row in data["unresolved_types"]:
        grouped[f"{row['type']} - {row['reason']}"].append(row["context"])
    lines.extend(
        _table(
            ["Type / reason", "Occurrences", "Example context"],
            [
                [key, str(len(contexts)), contexts[0]]
                for key, contexts in sorted(grouped.items())
            ],
        )
    )

    lines.append("## Structurally opaque payload types")
    lines.append("")
    lines.append(
        "Types with no static structure - `java.lang.Object`, `org.json.JSONObject`, "
        "qcadoo's dynamic `Entity`. These are emitted as `type: object` on purpose; "
        "no amount of static analysis can recover their shape."
    )
    lines.append("")
    opaque_grouped: Dict[str, List[str]] = defaultdict(list)
    for row in data.get("opaque_types", []):
        opaque_grouped[row["type"]].append(row["context"])
    lines.extend(
        _table(
            ["Type", "Uses", "Contexts"],
            [
                [key, str(len(contexts)), ", ".join(sorted(contexts)[:4])]
                for key, contexts in sorted(opaque_grouped.items())
            ],
        )
    )

    lines.append("## Unbound (`@ModelAttribute`-style) parameters")
    lines.append("")
    lines.append(
        "Parameters with no binding annotation. Spring 3.2 populates them from the query "
        "string field-by-field; the individual query keys are not modelled in the spec."
    )
    lines.append("")
    lines.extend(
        _table(
            ["Source", "Parameter", "Path"],
            [[row["source"], f"`{row['parameter']}`", f"`{row['path']}`"] for row in data["unbound_parameters"]],
        )
    )

    lines.append("## Summaries needing human curation")
    lines.append("")
    lines.append(
        "Every summary below is machine-derived. Add a `ClassName.methodName` entry to "
        "`tools/summaries.yml` to replace one, then regenerate."
    )
    lines.append("")
    lines.extend(
        _table(
            ["Source", "Generated summary"],
            [[row["source"], row["summary"]] for row in data["summaries_needing_curation"]],
        )
    )

    if data["path_conflicts"]:
        lines.append("## Path conflicts")
        lines.append("")
        lines.extend(f"- {conflict}" for conflict in data["path_conflicts"])
        lines.append("")

    lines.append("## Files written")
    lines.append("")
    lines.extend(f"- `{path}`" for path in data["files_written"])
    lines.append("")

    lines.append("## Full endpoint inventory")
    lines.append("")
    lines.extend(
        _table(
            ["Verb", "Path", "Source", "Return type", "Inherited"],
            [
                [
                    row["method"],
                    f"`{row['path']}`",
                    row["source"],
                    f"`{row['return_type']}`",
                    "yes" if row["inherited"] else "",
                ]
                for row in data["endpoints"]
            ],
        )
    )
    return "\n".join(lines)


def dump_json(data: Dict[str, object]) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False, sort_keys=False) + "\n"
